export function validateDiaryEntries(entries: readonly DiaryEntry[]) {
  const issues: string[] = []
  const expectedEntryCount = 83
  if (entries.length !== expectedEntryCount) issues.push(`日記は${expectedEntryCount}件必要です。`)
  if (Object.keys(DIARY_COLLECTION_BY_DATE).length !== expectedEntryCount) issues.push(`日記の図鑑対応表は${expectedEntryCount}件必要です。`)
  if (Object.keys(DIARY_CAT_FIRST_ENDINGS).length !== expectedEntryCount) issues.push(`日記の猫優先オチは${expectedEntryCount}件必要です。`)

  const dates = new Set<string>()
  const imagePaths = new Set<string>()
  const alts = new Set<string>()
  const punchlineTypes = new Set<DiaryPunchlineType>()
  const catFirstEndings = new Set<string>()

  for (const entry of entries) {
    if (dates.has(entry.date)) issues.push(entry.date + " の日付が重複しています。")
    dates.add(entry.date)

    const expectedImagePath = "/content/diary/" + entry.date + ".webp"
    if (entry.imagePath !== expectedImagePath) issues.push(entry.date + " の画像パスが日付と一致しません。")
    if (entry.illustration !== entry.imagePath) issues.push(entry.date + " の画像参照が一致しません。")
    if (imagePaths.has(entry.imagePath)) issues.push(entry.date + " の画像パスが重複しています。")
    imagePaths.add(entry.imagePath)

    if (!entry.alt.trim()) issues.push(entry.date + " の画像説明が空です。")
    if (alts.has(entry.alt)) issues.push(entry.date + " の画像説明が重複しています。")
    alts.add(entry.alt)

    const endingTemplate = DIARY_CAT_FIRST_ENDINGS[entry.date]
    const primaryCatName = DIARY_CAT_BY_ID[entry.catIds[0]]?.name
    if (!endingTemplate || !primaryCatName) {
      issues.push(entry.date + " の猫優先オチが設定されていません。")
    } else {
      const expectedEnding = endingTemplate.replaceAll("{cat}", primaryCatName)
      if (!entry.body.endsWith(expectedEnding)) issues.push(entry.date + " の本文末尾と猫優先オチが一致しません。")
      if (!expectedEnding.includes("なおくん") || !expectedEnding.includes("うんち")) {
        issues.push(entry.date + " の猫優先オチになおくんの現状がありません。")
      }
      if (!expectedEnding.includes(primaryCatName)) issues.push(entry.date + " の猫優先オチに主役猫がいません。")
      catFirstEndings.add(expectedEnding)
    }

    const transformationSentence = entry.body
      .split("。")
      .find((sentence) => sentence.includes("変身") && /うんち[^。]{0,40}(?:に|へ)変身/.test(sentence))
    if (entry.collectionId) {
      if (!transformationSentence) {
        issues.push(entry.date + " の専用フォーム回に、なおくんの変身が明記されていません。")
      } else if (!DIARY_SAFE_TRANSFORMATION_CUES.some((cue) => transformationSentence.includes(cue))) {
        issues.push(entry.date + " の変身文に安全な魔法の説明がありません。")
      }
    } else if (transformationSentence || DIARY_SAFE_TRANSFORMATION_CUES.some((cue) => entry.body.includes(cue))) {
      issues.push(entry.date + " の日常回に、定型的な変身展開が残っています。")
    }
    if (/[叩踏殴蹴舐]|猫パンチ|なめ/.test(entry.body + entry.miyukiNote)) {
      issues.push(entry.date + " に強い接触表現があります。")
    }

    if (entry.collectionId && !DIARY_COLLECTION_IDS.includes(entry.collectionId)) issues.push(entry.date + " の図鑑IDが不正です。")
    const expectedCollectionId = DIARY_COLLECTION_BY_DATE[entry.date]
    if (!expectedCollectionId) {
      issues.push(entry.date + " の図鑑対応が監査されていません。")
    } else if (expectedCollectionId === "naokun-poop-classic") {
      if (entry.collectionId) issues.push(entry.date + " の日常回で変身カードが解放されます。")
    } else if (entry.collectionId !== expectedCollectionId) {
      issues.push(entry.date + " の専用フォームが挿絵の役と一致しません。")
    }
    if (entry.catIds.length === 0 || entry.catIds.some((catId) => !DIARY_CAT_IDS.includes(catId))) {
      issues.push(entry.date + " の猫IDが不正です。")
    }
    for (const catId of entry.catIds) {
      const cat = DIARY_CAT_BY_ID[catId]
      if (cat && !(entry.title + entry.body + entry.alt).includes(cat.name)) {
        issues.push(entry.date + " の猫ID「" + catId + "」と本文の名前「" + cat.name + "」が一致しません。")
      }
    }
    for (const cat of DIARY_CATS) {
      if ((entry.title + entry.body + entry.alt).includes(cat.name) && !entry.catIds.includes(cat.id)) {
        issues.push(entry.date + " に「" + cat.name + "」が登場しますが、猫ID「" + cat.id + "」がありません。")
      }
    }

    for (const item of entry.glossary) {
      if (!item.term.trim() || !item.reading.trim() || !item.meaning.trim()) {
        issues.push(entry.date + " のことばのヒントに空欄があります。")
      }
    }

    punchlineTypes.add(entry.punchlineType)
  }

  for (const mappedDate of Object.keys(DIARY_COLLECTION_BY_DATE)) {
    if (!dates.has(mappedDate)) issues.push(mappedDate + " の図鑑対応に日記がありません。")
  }

  if (punchlineTypes.size < 8) issues.push("オチの構造は8種類以上必要です。")
  if (catFirstEndings.size !== entries.length) issues.push("猫優先オチは全日程で違う文章にしてください。")
  return issues
}

export const DIARY_ENTRY_VALIDATION_ISSUES = validateDiaryEntries(DIARY_ENTRIES)

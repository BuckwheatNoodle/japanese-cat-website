import { createHash } from "node:crypto"
import { access, mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises"
import path from "node:path"
import process from "node:process"
import { fileURLToPath } from "node:url"

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(scriptDirectory, "..")

function normalizeBasePath(value) {
  if (!value || value === "/") return ""
  const withLeadingSlash = value.startsWith("/") ? value : `/${value}`
  return withLeadingSlash.replace(/\/$/, "")
}

function resolveOutDirectory() {
  const flagIndex = process.argv.indexOf("--out-dir")
  const fromFlag = flagIndex >= 0 ? process.argv[flagIndex + 1] : undefined
  return path.resolve(projectRoot, fromFlag || "out")
}

async function walkFiles(directory, relativeDirectory = "") {
  const entries = await readdir(path.join(directory, relativeDirectory), { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const relativePath = path.posix.join(relativeDirectory.split(path.sep).join(path.posix.sep), entry.name)
    if (entry.isDirectory()) files.push(...(await walkFiles(directory, relativePath)))
    else if (entry.isFile()) files.push(relativePath)
  }

  return files
}

function isCoreAsset(relativePath) {
  if (["index.html", "404.html", "offline.html", "manifest.webmanifest"].includes(relativePath)) return true
  if (relativePath.startsWith("pwa/")) return true

  if (relativePath.startsWith("_next/static/")) {
    return /\.(?:js|css|woff2?|json)$/i.test(relativePath) && !relativePath.endsWith(".map")
  }

  if (/^skins\/cream-soda\/(?:hero-cafe-v2|activity-(?:coloring|fortune|diary)|footer-trim-cropped|nav-(?:home|games|coloring|fortune|diary))\.webp$/i.test(relativePath)) {
    return true
  }

  if (/^(?:content\/missions\/daily-board|skins\/cream-soda\/passport\/(?:today-board|stamp-(?:games|coloring|fortune|diary)))\.webp$/i.test(relativePath)) {
    return true
  }

  return false
}

function isRuntimeImageAsset(relativePath) {
  return /\.(?:avif|gif|ico|jpe?g|png|svg|webp)$/i.test(relativePath)
}

async function buildPrecache(outDirectory, basePath) {
  const allFiles = (await walkFiles(outDirectory)).sort()
  const files = allFiles.filter(isCoreAsset)
  const runtimeImages = allFiles.filter((relativePath) => !isCoreAsset(relativePath) && isRuntimeImageAsset(relativePath))
  const hash = createHash("sha256")
  let totalBytes = 0

  for (const relativePath of files) {
    const filePath = path.join(outDirectory, ...relativePath.split("/"))
    const metadata = await stat(filePath)
    totalBytes += metadata.size
    hash.update(relativePath)
    hash.update(await readFile(filePath))
  }

  // Runtime images are not precached, but their contents must still revise the
  // worker so an asset-only deployment can retire an older runtime image cache.
  for (const relativePath of runtimeImages) {
    const filePath = path.join(outDirectory, ...relativePath.split("/"))
    hash.update(`runtime-image:${relativePath}`)
    hash.update(await readFile(filePath))
  }

  const urls = files.map((relativePath) => `${basePath}/${relativePath}`)
  return { urls, version: hash.digest("hex").slice(0, 12), totalBytes }
}

function createServiceWorker({ urls, version, basePath }) {
  const scopeId = createHash("sha256").update(basePath || "/").digest("hex").slice(0, 32)
  const cachePrefix = `miyuki-${scopeId}-`
  const precacheName = `${cachePrefix}precache-${version}`
  const imageCacheName = `${cachePrefix}runtime-images-${version}`
  const offlineUrl = `${basePath}/offline.html`
  const appShellUrl = `${basePath}/index.html`

  return `/* Generated by scripts/generate-service-worker.mjs. Do not edit directly. */
const PRECACHE_NAME = ${JSON.stringify(precacheName)};
const IMAGE_CACHE_NAME = ${JSON.stringify(imageCacheName)};
const CACHE_PREFIX = ${JSON.stringify(cachePrefix)};
const PRECACHE_URLS = ${JSON.stringify(urls, null, 2)};
const OFFLINE_URL = ${JSON.stringify(offlineUrl)};
const APP_SHELL_URL = ${JSON.stringify(appShellUrl)};
const IMAGE_CACHE_LIMIT = 80;

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(PRECACHE_NAME).then((cache) => cache.addAll(PRECACHE_URLS)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(
        names
          .filter((name) => name.startsWith(CACHE_PREFIX) && name !== PRECACHE_NAME && name !== IMAGE_CACHE_NAME)
          .map((name) => caches.delete(name)),
      ))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
});

async function trimImageCache() {
  const cache = await caches.open(IMAGE_CACHE_NAME);
  const requests = await cache.keys();
  const excess = requests.length - IMAGE_CACHE_LIMIT;
  if (excess > 0) await Promise.all(requests.slice(0, excess).map((request) => cache.delete(request)));
}

async function matchNamedCache(cacheName, request) {
  try {
    const cache = await caches.open(cacheName);
    return await cache.match(request);
  } catch (error) {
    console.warn("Named cache lookup failed", error);
    return undefined;
  }
}

async function fetchAndRefreshImage(request) {
  const response = await fetch(request);
  if (response.ok && response.type === "basic") {
    try {
      const cache = await caches.open(IMAGE_CACHE_NAME);
      await cache.put(request, response.clone());
      await trimImageCache();
    } catch (error) {
      // Cache storage is best-effort. Never discard a valid network response
      // just because quota, privacy settings, or eviction blocked cache.put().
      console.warn("Image cache refresh failed", error);
    }
  }
  return response;
}

async function cacheImage(request, networkResponse) {
  const cached = await matchNamedCache(IMAGE_CACHE_NAME, request);

  if (cached) return cached;

  try {
    return await networkResponse;
  } catch (error) {
    const fallback = await matchNamedCache(IMAGE_CACHE_NAME, request);
    if (fallback) return fallback;
    throw error;
  }
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  const isMedia = request.destination === "audio" || request.destination === "video" || /\\.(?:mp3|m4a|ogg|wav|webm|mp4)$/i.test(url.pathname);
  if (request.headers.has("range") || isMedia) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => response)
        .catch(async () =>
          (await matchNamedCache(PRECACHE_NAME, request)) ||
          (await matchNamedCache(PRECACHE_NAME, APP_SHELL_URL)) ||
          matchNamedCache(PRECACHE_NAME, OFFLINE_URL),
        ),
    );
    return;
  }

  if (request.destination === "image") {
    const networkResponse = fetchAndRefreshImage(request);
    event.waitUntil(networkResponse.then(() => undefined).catch(() => undefined));
    event.respondWith(cacheImage(request, networkResponse));
    return;
  }

  event.respondWith(matchNamedCache(PRECACHE_NAME, request).then((cached) => cached || fetch(request)));
});
`
}

async function main() {
  const outDirectory = resolveOutDirectory()
  const requiredFiles = ["index.html", "offline.html", "manifest.webmanifest", "pwa/icon-192.png"]

  for (const relativePath of requiredFiles) {
    const filePath = path.join(outDirectory, ...relativePath.split("/"))
    try {
      await access(filePath)
    } catch {
      throw new Error(`Required static export file not found at ${filePath}. Run \"next build\" first.`)
    }
  }

  const basePath = normalizeBasePath(process.env.NEXT_PUBLIC_BASE_PATH)
  const precache = await buildPrecache(outDirectory, basePath)
  const maxRecommendedBytes = 8 * 1024 * 1024
  if (precache.totalBytes > maxRecommendedBytes) {
    console.warn(`Core precache is ${(precache.totalBytes / 1024 / 1024).toFixed(1)} MB; consider reducing it below 8 MB.`)
  }

  await mkdir(outDirectory, { recursive: true })
  await writeFile(
    path.join(outDirectory, "sw.js"),
    createServiceWorker({ ...precache, basePath }),
    "utf8",
  )

  console.log(
    `Generated ${path.join(outDirectory, "sw.js")} with ${precache.urls.length} core files (${(
      precache.totalBytes / 1024 / 1024
    ).toFixed(2)} MB).`,
  )
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
